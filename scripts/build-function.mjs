// Bundles the game server (engine + content + handler) into one ES module for the `game` Edge Function.
// Run before `supabase functions deploy game`.
import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const result = await build({
  entryPoints: [`${root}packages/server/src/index.ts`],
  outfile: `${root}supabase/functions/game/game.js`,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minifySyntax: true,
  legalComments: 'none',
  banner: { js: '// Generated by scripts/build-function.mjs. Do not edit.' },
  metafile: true,
});
const bytes = Object.values(result.metafile.outputs)[0].bytes;
console.log(`game.js: ${(bytes / 1024).toFixed(1)} KB`);
